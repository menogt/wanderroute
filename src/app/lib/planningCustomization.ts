export type ArrangementStatus = "PROPOSED" | "NEEDS_BOOKING" | "TRAVELLER_BOOKED" | "CHANGED_CANCELLED";
export type StayChoice = { name?: string; placeId?: string; area?: string; rooms?: number;
  status: ArrangementStatus; notes?: string; nightlyRoomAmount?: number; rateCurrency?: TripBriefV1["budget"]["currency"] };
export type DestinationChoice = { city: string; nights: number; requirement: "MUST" | "OPTIONAL"; locked?: boolean };
export type PlanningCustomization = { stops: DestinationChoice[]; stays: Record<string, StayChoice>;
  transport: Record<string, { mode: TransportMode; status: ArrangementStatus; notes?: string }>;
  wishlist: { city: string; requirement: "MUST" | "OPTIONAL" | "EXCLUDED"; role: "VISIT" | "BASE" }[] };
export type CustomizationDraft = PlanningCustomization & { brief: TripBriefV1 };

export function customizationDraft(session: PlanningV2Session): CustomizationDraft {
  const concept = session.result!.concepts.find(concept => concept.routeConcept.id === session.selectedConceptId)!;
  return structuredClone({ brief: session.result!.brief, stops: concept.routeConcept.stops.map(stop => ({
    city: stop.destinationName, nights: stop.nights, requirement: "OPTIONAL" as const })), stays: {}, transport: {}, wishlist: [],
    ...session.detailed?.customization });
}

function activitySelection(item: NonNullable<PlanningV2Session["detailed"]>["itinerary"]["days"][number]["items"][number]): ActivitySelection {
  return { id: item.id, placeId: item.placeId ?? "", description: item.detail, durationMinutes: item.durationMinutes,
    preferredStart: item.preferredStart, isFreeTime: item.isFreeTime };
}

/** Preview and apply use the same deterministic calculation. Nothing is regenerated by AI. */
export function previewPlanningCustomization(session: PlanningV2Session, draft: CustomizationDraft,
  places: CandidatePlace[] = session.detailed!.places): { session?: PlanningV2Session; problems: string[]; consequences: string[] } {
  const problems: string[] = [];
  const consequences: string[] = [];
  const previous = session.detailed!;
  const old = customizationDraft(session);
  const brief = { ...draft.brief, requestedCities: [...new Set([...draft.stops.map(stop => stop.city),
    ...draft.wishlist.filter(item => item.requirement !== "EXCLUDED").map(item => item.city)])] };
  problems.push(...validatePlanningBrief(brief).filter(issue => issue.severity === "ERROR").map(issue => issue.detail!));
  const nights = draft.stops.reduce((sum, stop) => sum + stop.nights, 0);
  if (!draft.stops.length || draft.stops.length > 8 || draft.stops.some(stop => !Number.isInteger(stop.nights) || stop.nights < 1)) problems.push("Choose one to eight overnight bases, with at least one night at each.");
  if (nights !== brief.durationDays - 1) problems.push(`${brief.durationDays} days allow ${brief.durationDays - 1} nights. You allocated ${nights}; adjust an unlocked stay or change the trip length.`);
  if (new Set(draft.stops.map(stop => stop.city.toLowerCase())).size !== draft.stops.length) problems.push("Each overnight base should appear once; add nights to its existing stay.");
  const datesAt = (stops: DestinationChoice[], city: string) => {
    const index = stops.findIndex(stop => stop.city === city);
    return index < 0 ? "removed" : `${stops.slice(0, index).reduce((sum, stop) => sum + stop.nights, 0)}:${stops[index].nights}`;
  };
  for (const stop of old.stops) {
    const changed = datesAt(old.stops, stop.city) !== datesAt(draft.stops, stop.city) ||
      planningDate(old.brief, 0) !== planningDate(brief, 0);
    if (stop.locked && draft.stops.find(item => item.city === stop.city)?.locked !== false && changed) problems.push(`Unlock ${stop.city} before changing its dates or nights.`);
    const stay = old.stays[stop.city];
    if (stay?.status === "TRAVELLER_BOOKED" && draft.stays[stop.city]?.status !== "CHANGED_CANCELLED" &&
      (changed || JSON.stringify(stay) !== JSON.stringify(draft.stays[stop.city]))) problems.push(`Your recorded booking in ${stop.city} is protected. Record a change/cancellation first if the reservation has changed.`);
    if (stop.requirement === "MUST" && !draft.stops.some(item => item.city === stop.city) &&
      !draft.wishlist.some(item => item.city === stop.city)) problems.push(`Keep ${stop.city}, or explicitly mark it optional before removing it.`);
  }
  for (const [city, stay] of Object.entries(draft.stays)) {
    if (stay.rooms !== undefined && (!Number.isInteger(stay.rooms) || stay.rooms < 1 || stay.rooms > 12)) problems.push(`Enter one to twelve rooms for ${city}.`);
    if (stay.nightlyRoomAmount !== undefined && (!Number.isFinite(stay.nightlyRoomAmount) || stay.nightlyRoomAmount < 0 || stay.nightlyRoomAmount > 10000000 || !stay.rooms)) problems.push(`Enter a nonnegative room rate and an explicit room count for ${city}.`);
    if (stay.placeId && !places.some(place => place.databaseId === stay.placeId && place.city === city && place.category === "hotel")) problems.push(`Choose a catalog property in ${city}.`);
  }
  if (problems.length) return { problems, consequences };
  const available = knownPlanningDestinations();
  const destinations: PlanningDestination[] = draft.stops.map(stop => {
    const found = available.find(item => item.name === stop.city);
    return { ...(found ?? { id: stop.city, name: stop.city }), requested: true };
  });
  const matrix = session.result!.matrix;
  const legs = destinations.slice(1).map((to, index) => matrixLeg(matrix, destinations[index].id, to.id) ??
    { fromId: destinations[index].id, toId: to.id, status: "UNAVAILABLE" as const });
  const reasons: RouteReason[] = assessRouteConstraints(brief, destinations, legs, matrix);
  for (const stop of destinations) {
    const season = assessPlanningSeason(stop.name, planningSeasonMonth(brief));
    if (season.status !== "SUITABLE") reasons.push({ code: `SEASON_${season.status === "AVOID" ? "AVOID" : season.status === "CAUTION" ? "CAUTION" : "UNKNOWN"}`, severity: season.status === "UNKNOWN" ? "UNCERTAIN" : "PENALTY", destinations: [stop.name] });
  }
  const scored = scoreRoute(brief, destinations, legs, reasons);
  const route: CandidateRoute = { id: `route:${destinations.map(stop => encodeURIComponent(stop.id)).join(">")}`, routingBasis: "ROAD_DRIVING", destinations,
    nights: draft.stops.map(stop => stop.nights), legs, reasons: scored.reasons, score: scored.score,
    feasibility: reasons.some(reason => reason.severity === "REJECTION") ? "REJECTED" : "UNCERTAIN" };
  const assignments = Object.fromEntries(Object.entries(draft.transport).map(([id, value]) => [id, value.mode]));
  const concept = createConcept(brief, route, matrix, { assignments });
  if (concept.readiness === "INVALID") return { problems: concept.issues.filter(issue => issue.severity === "ERROR").map(issue => issue.detail!), consequences };
  const nextLegs = [...concept.transport.legs, concept.transport.arrivalTransfer, concept.transport.departureTransfer].filter(Boolean);
  for (const [id, choice] of Object.entries(old.transport)) {
    if (choice.status === "TRAVELLER_BOOKED" && draft.transport[id]?.status !== "CHANGED_CANCELLED" &&
      (!nextLegs.some(leg => leg!.id === id && leg!.mode === choice.mode) ||
        JSON.stringify(old.brief.arrival) !== JSON.stringify(brief.arrival) ||
        JSON.stringify(old.brief.departure) !== JSON.stringify(brief.departure) ||
        JSON.stringify(old.stops) !== JSON.stringify(draft.stops))) problems.push(`Your recorded transfer ${id.replace(">", " to ")} is protected. Record its change/cancellation before changing its route or date.`);
  }
  if (problems.length) return { problems, consequences };
  const result = { ...session.result!, brief, destinations, concepts: [concept, ...session.result!.concepts.filter(item => item.routeConcept.id !== route.id)] };
  const cities = routeDayCities(route, brief.durationDays);
  const selections: DaySelection[] = cities.map(() => ({ placeIds: [], activities: [] }));
  const shortlist = [...(previous.unscheduledActivities ?? [])];
  const used = new Set<string>();
  for (const oldDay of previous.itinerary.days) {
    const compatible = cities.map((city, i) => ({ city, i })).filter(item => item.city === oldDay.city);
    for (const item of oldDay.items.filter(item => item.category === "activity")) {
      if (used.has(item.id)) continue;
      const target = compatible.find(target => target.i === oldDay.day - 1 && selections[target.i].activities!.length < 6) ??
        compatible.find(target => selections[target.i].activities!.length < 6 && !selections[target.i].activities!.some(existing => item.placeId && existing.placeId === item.placeId));
      if (target) { selections[target.i].activities!.push(activitySelection(item)); used.add(item.id); }
      else shortlist.push({ ...activitySelection(item), city: oldDay.city, label: item.label });
    }
  }
  for (const day of selections) day.placeIds = day.activities!.map(item => item.placeId);
  const customization = { stops: draft.stops, stays: draft.stays, transport: draft.transport, wishlist: draft.wishlist };
  const detailed = buildDetailedPlanningResult(result, route.id, places, selections, previous.generationMode,
    previous.generationIssue, previous.ledger.exchangeRates, customization);
  detailed.unscheduledActivities = shortlist;
  detailed.allowances = brief.budget.currency === old.brief.budget.currency ? previous.allowances : undefined;
  if (brief.budget.currency !== old.brief.budget.currency && previous.allowances) consequences.push("Your allowances will be cleared because their currency changed. Re-enter them in the new currency; Undo restores them.");
  consequences.push(detailed.ledger.summary.trip.minimum > 0 ? `${brief.budget.currency} ${detailed.ledger.summary.trip.minimum.toLocaleString()} in supported or traveler-recorded amounts; additional costs remain unpriced.` : "Rates are still unknown; use your own planning allowances until quotes or sourced prices are available.");
  consequences.push(`${brief.durationDays} days, ${nights} nights across ${draft.stops.length} bases. Existing compatible activities keep their IDs.`);
  if (shortlist.length) consequences.push(`${shortlist.length} activities remain in your unscheduled shortlist; none are discarded.`);
  for (const item of draft.wishlist.filter(item => item.role === "VISIT" && item.requirement !== "EXCLUDED")) consequences.push(`${item.city} is a requested visit, not an overnight base. It still needs a compatible day and transfer before it can be counted as included.`);
  consequences.push("Unpriced costs and unverified journeys stay unknown. No reservation is made or changed.");
  if (detailed.validation.errors.some(issue => !["BUDGET_OVER", "MUST_VISIT_UNSCHEDULED"].includes(issue.code))) return { problems: detailed.validation.errors.filter(issue => !["BUDGET_OVER", "MUST_VISIT_UNSCHEDULED"].includes(issue.code)).map(issue => issue.code.toLowerCase().replace(/_/g, " ")), consequences };
  return { problems, consequences, session: { ...session, view: "itinerary", result, brief, selectedConceptId: route.id, detailed,
    editPast: [...(session.editPast ?? []), previous].slice(-20), editFuture: [], editError: undefined } };
}
